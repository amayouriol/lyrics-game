/** Rule checks for choosing a YouTube video: run with `npm test`. */
import { test } from "node:test";
import assert from "node:assert/strict";
import {
  cleanSongTitle,
  decodeEntities,
  isAutoGenerated,
  looksLikeLyricsVideo,
  looksLikeOtherVersion,
  parseDuration,
  rankCandidates,
  searchQuery,
  warningFor,
  type VideoCandidate,
} from "./youtube.ts";

const video = (over: Partial<VideoCandidate>): VideoCandidate => ({
  videoId: "aaaaaaaaaaa",
  title: "Song",
  channel: "Channel",
  thumbnail: null,
  durationMs: 200_000,
  topic: false,
  warning: null,
  ...over,
});

test("song titles lose the extras that spoil a search", () => {
  assert.equal(cleanSongTitle("Dancing Queen (feat. Someone)"), "Dancing Queen");
  assert.equal(cleanSongTitle("Hey Jude - Remastered 2015"), "Hey Jude");
  assert.equal(cleanSongTitle("Yellow - Radio Edit"), "Yellow");
  assert.equal(cleanSongTitle("Let It Be [2009 Remaster]"), "Let It Be");
  assert.equal(cleanSongTitle("Plain Title"), "Plain Title");
  assert.equal(cleanSongTitle("Lose Yourself (Soundtrack Version)"), "Lose Yourself");
});

test("the search uses the main artist and the clean title", () => {
  assert.equal(searchQuery("Hey Jude - Remastered 2015", "The Beatles"), "The Beatles Hey Jude");
});

test("lyrics videos are spotted in English and Spanish", () => {
  assert.ok(looksLikeLyricsVideo("Adele - Hello (Lyrics)"));
  assert.ok(looksLikeLyricsVideo("Queen - Bohemian Rhapsody (Official Lyric Video)"));
  assert.ok(looksLikeLyricsVideo("Shakira - Waka Waka (Letra)"));
  assert.ok(looksLikeLyricsVideo("Hello karaoke version"));
  assert.ok(looksLikeLyricsVideo("Hello sing along"));
  assert.ok(!looksLikeLyricsVideo("Adele - Hello (Official Music Video)"));
  assert.ok(!looksLikeLyricsVideo("Hello - Topic"));
});

test("other versions are spotted, unless the song itself is one", () => {
  assert.ok(looksLikeOtherVersion("Hello (Live at Royal Albert Hall)", "Hello"));
  assert.ok(looksLikeOtherVersion("Hello - Slowed + Reverb", "Hello"));
  assert.ok(!looksLikeOtherVersion("Hello (Official Video)", "Hello"));
  assert.ok(!looksLikeOtherVersion("Alive (Live)", "Alive (Live)"));
});

test("auto-generated uploads are recognised", () => {
  assert.ok(isAutoGenerated("Adele - Topic", ""));
  assert.ok(isAutoGenerated("Adele", "Provided to YouTube by XL Recordings\n\nHello"));
  assert.ok(!isAutoGenerated("AdeleVEVO", "Official video"));
});

test("durations in YouTube's format are read", () => {
  assert.equal(parseDuration("PT3M33S"), 213_000);
  assert.equal(parseDuration("PT1H2M3S"), 3_723_000);
  assert.equal(parseDuration("PT45S"), 45_000);
  assert.equal(parseDuration("P0D"), 0);
});

test("titles from YouTube have their HTML codes turned back into characters", () => {
  assert.equal(decodeEntities("Guns N&#39; Roses &amp; Friends &quot;Live&quot;"), "Guns N' Roses & Friends \"Live\"");
});

test("a warning says why a video looks wrong", () => {
  const song = { title: "Hello", durationMs: 295_000 };
  assert.equal(warningFor({ title: "Hello (Lyrics)", durationMs: 295_000 }, song), "lyrics");
  assert.equal(warningFor({ title: "Hello (Live)", durationMs: 295_000 }, song), "version");
  assert.equal(warningFor({ title: "Hello", durationMs: 340_000 }, song), "length");
  assert.equal(warningFor({ title: "Hello", durationMs: 296_000 }, song), null);
  // A lyrics channel counts even when the title doesn't say so.
  assert.equal(
    warningFor({ title: "Adele - Hello", channel: "Amazing Lyrics", durationMs: 295_000 }, song),
    "lyrics"
  );
});

test("ranking puts the clean upload first and lyrics videos last", () => {
  const lyrics = video({ videoId: "lyrics", warning: "lyrics" });
  const official = video({ videoId: "official" });
  const topic = video({ videoId: "topic", topic: true });
  const ranked = rankCandidates([lyrics, official, topic], { durationMs: 200_000 });
  assert.deepEqual(
    ranked.map((v) => v.videoId),
    ["topic", "official", "lyrics"]
  );
});

test("ranking keeps YouTube's order between equal videos", () => {
  const a = video({ videoId: "a" });
  const b = video({ videoId: "b" });
  assert.deepEqual(
    rankCandidates([a, b], { durationMs: 200_000 }).map((v) => v.videoId),
    ["a", "b"]
  );
});

test("a video of the right length beats one that's off, all else equal", () => {
  const off = video({ videoId: "off", durationMs: 260_000, warning: "length" });
  const right = video({ videoId: "right", durationMs: 201_000 });
  assert.equal(rankCandidates([off, right], { durationMs: 200_000 })[0].videoId, "right");
});
